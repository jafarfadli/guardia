// Generates every tool's config from design/tokens.json (the material list).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(join(root, 'design/tokens.json'), 'utf8'));

function out(rel, text) {
  const p = join(root, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, text);
  console.log('wrote', rel);
}

out('wallpaper/src/tokens.gen.js', `// Generated by scripts/build-themes.mjs from design/tokens.json. Do not edit.\nexport const TOKENS = ${JSON.stringify(tokens, null, 2)};\n`);

// ---------------------------------------------------------------- Swift (Kamar app)
{
  const rgb = (h) => { const n = parseInt(h.slice(1), 16); return [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((v) => (v / 255).toFixed(4)); };
  const col = (h) => { const [r, g, b] = rgb(h); return `NSColor(srgbRed: ${r}, green: ${g}, blue: ${b}, alpha: 1)`; };
  const u = tokens.ui, p = tokens.palette;
  const scheme = (s) => `Scheme(paper: ${col(s.surfaceRaised)}, paperEdge: ${col(s.surface)}, ink: ${col(s.text)}, inkSoft: ${col(s.textMuted)}, accent: ${col(s.accent)}, shadow: ${col(s.shadow)})`;
  out('kamar-app/Sources/Theme.gen.swift', `// Generated by scripts/build-themes.mjs from design/tokens.json. Do not edit.
import AppKit

struct Scheme {
    let paper: NSColor, paperEdge: NSColor, ink: NSColor, inkSoft: NSColor, accent: NSColor, shadow: NSColor
}

enum Theme {
    static let light = ${scheme(u.light)}
    static let dark = ${scheme(u.dark)}
    static let mustard = ${col(p.mustard)}
    static let terracotta = ${col(p.terracotta)}
    static let teal = ${col(p.teal)}
    static let olive = ${col(p.olive)}
    static let mutedRed = ${col(p['muted-red'])}
    static let navy = ${col(p.navy)}
    static let cream = ${col(p.cream)}
    static let lettering = "${tokens.fonts.lettering}"
    static let mono = "${tokens.fonts.mono}"
}
`);
}

