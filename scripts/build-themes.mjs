// ---------------------------------------------------------------- contrast check (WCAG)
function lum(h) {
  const n = parseInt(h.slice(1, 7), 16);
  const c = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; });
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
}
const contrast = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };
for (const mode of ['light', 'dark']) {
  const s = tokens.ui[mode];
  const checks = { text: s.text, textMuted: s.textMuted, accent: s.accent, ...s.syntax };
  const low = Object.entries(checks).map(([k, v]) => [k, contrast(v, s.bg)]).filter(([k, r]) => r < (k === 'comment' ? 3 : 4.5));
  console.log(`contrast ${mode}:`, low.length ? low.map(([k, r]) => `${k} ${r.toFixed(2)}`).join(', ') : 'all pass');
}

